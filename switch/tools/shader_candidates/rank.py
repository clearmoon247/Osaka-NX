# Ranks the combiner words found by scan.c (ROM data) and extract.py/gen (decomp source) and writes shader_candidates.h.
import re,collections,pickle,sys,os
keys,inv,where=pickle.load(open('inv.pkl','rb'))
words=dict(l.split() for l in open('src_words.txt'))
srccount=collections.Counter()
for i,k in enumerate(keys): srccount[words[str(i)][2:]]+=inv[k]
romblocks=collections.defaultdict(set)
for l in open('hits.txt'):
    m,same,tag=l.split(); romblocks[m].add(tag)
cand=set(srccount)|set(romblocks)
def score(m): return srccount[m]*3+len(romblocks[m])
def same(m):
    w0=int(m[:6],16); w1=int(m[6:],16)
    f=lambda w0,w1:((w0>>20)&15,(w1>>28)&15,(w0>>15)&31,(w1>>15)&7,(w0>>12)&7,(w1>>12)&7,(w0>>9)&7,(w1>>9)&7)
    g=lambda w0,w1:(((w0>>5)&15),(w1>>24)&15,w0&31,(w1>>6)&7,(w1>>21)&7,(w1>>3)&7,(w1>>18)&7,w1&7)
    return f(w0,w1)==g(w0,w1)
known=set(re.findall(r'0x([0-9A-F]{16})ULL',open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','render_gliden64.cpp')).read().split('SHADER_SEED')[1].split('};')[0]))
def variants(m,s):
    if same(m): v=['38','39']            # 1-cycle: triangle or rect
    else:       v=['3A']+(['3B'] if s>=13 else [])   # 2-cycle: mostly triangle
    return [x+m for x in v]
likely=[];rare=[]
for m in sorted(cand,key=lambda m:(-score(m),m)):
    s=score(m)
    ks=[k for k in variants(m,s) if k not in known]
    (likely if s>=2 else rare).extend(ks)
print('known',len(known),'likely keys',len(likely),'rare keys',len(rare),file=sys.stderr)
def fmt(lst):
    out=[]
    for i in range(0,len(lst),4): out.append('        '+', '.join('0x%sULL'%k for k in lst[i:i+4])+',')
    return '\n'.join(out)
open('shader_candidates.h','w').write('''// Generated by switch/tools/shader_candidates (scan of the US v1.0 ROM + decomp source); do not edit by hand.
// GLideN64 combiner keys the game MAY draw with: every G_SETCOMBINE word found in the ROM's display-list data (Yay0 blocks decompressed)
// and in the decomp's gDPSetCombine* macros. The word is the key's low 56 bits. The top byte is the mode: 0x38 triangle / 0x39 rect with
// the 1-cycle combiner, 0x3A / 0x3B with a 2-cycle one (the 1-cycle test: both cycles identical), bilerp = 3, HWL on (as in every key seen).
// Ranked by how often the word occurs (source use counts 3, each Yay0 block 1). LIKELY = seen at least twice, RARE = seen once (mostly
// stray data or very specific effects). 45 of the 47 keys the game really built are in this scan's output (41 of 45 distinct words).
namespace {
    constexpr unsigned long long SHADER_LIKELY[] = {
'''+fmt(likely)+'''
    };
    constexpr unsigned long long SHADER_RARE[] = {
'''+fmt(rare)+'''
    };
}
''')
